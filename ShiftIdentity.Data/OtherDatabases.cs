using System.Security.Cryptography;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.ChangeTracking;
using Microsoft.EntityFrameworkCore.Metadata;
using Microsoft.EntityFrameworkCore.Storage.ValueConversion;

namespace ShiftSoftware.ShiftIdentity.Data;

/// <summary>
/// What the identity model needs on a database other than SQL Server. <see cref="ShiftIdentityDbContext"/> calls it
/// only when the context is not on SQL Server, so a SQL Server model, and its migrations, are exactly as they were.
/// </summary>
internal static class OtherDatabases
{
    /// <summary>EF's provider name for SQLite, which is what <c>Database.ProviderName</c> returns and <c>Database.IsSqlite()</c> compares.</summary>
    internal const string SqliteProviderName = "Microsoft.EntityFrameworkCore.Sqlite";

    // Marks a row version this context fills in itself, so a concurrency token the consumer manages is never touched.
    private const string AppSetRowVersion = "ShiftIdentity:AppSetRowVersion";

    /// <summary>
    /// <list type="bullet">
    /// <item>The identity's check constraints and collations are SQL Server's (<c>DATALENGTH</c>, <c>Latin1_General_100_BIN2</c>):
    /// they are left out. The identity's own tables only; the consumer's are not touched. Text then compares as the
    /// database does.</item>
    /// <item>The identity's row versions (<c>IsRowVersion</c>) are generated by SQL Server: elsewhere they stay concurrency
    /// tokens, and the context sets a new value on every insert and update (<see cref="SetRowVersions"/>).</item>
    /// <item>On SQLite only, which cannot sort or compare <c>DateTimeOffset</c> in a query, every <c>DateTimeOffset</c>
    /// property without a converter of its own is stored as its UTC ticks (<see cref="UtcTicks"/>). Every entity, the
    /// consumer's included.</item>
    /// <item>On SQLite only, which has no schemas, a table in a schema is named <c>{schema}_{table}</c>: the identity's
    /// tables are in the <c>ShiftIdentity</c> schema, and a consumer's <c>Brands</c> or <c>Countries</c> table would
    /// otherwise collide with the identity's. Every entity, the consumer's included.</item>
    /// </list>
    /// </summary>
    internal static void AdaptModel(ModelBuilder builder, bool sqlite)
    {
        var identityAssembly = typeof(ShiftIdentityDbContext).Assembly;
        foreach (var entity in builder.Model.GetEntityTypes())
        {
            if (sqlite && entity.BaseType is null && entity.GetTableName() is { } table && entity.GetSchema() is { Length: > 0 } schema)
            {
                entity.SetTableName($"{schema}_{table}");
                entity.SetSchema(null);
            }

            var identityEntity = entity.ClrType.Assembly == identityAssembly;
            if (identityEntity)
                foreach (var check in entity.GetCheckConstraints().ToList())
                    entity.RemoveCheckConstraint(check.ModelName);

            foreach (var property in entity.GetDeclaredProperties())
            {
                if (identityEntity)
                {
                    property.SetCollation(null);
                    if (property.ClrType == typeof(byte[]) && property.IsConcurrencyToken && property.ValueGenerated == ValueGenerated.OnAddOrUpdate)
                    {
                        property.ValueGenerated = ValueGenerated.Never;
                        property.SetAnnotation(AppSetRowVersion, true);
                    }
                }

                if (sqlite && (property.ClrType == typeof(DateTimeOffset) || property.ClrType == typeof(DateTimeOffset?)) &&
                    property.GetValueConverter() is null && property.GetProviderClrType() is null)
                    property.SetValueConverter(UtcTicks);
            }
        }
    }

    /// <summary>
    /// <c>DateTimeOffset</c> as its UTC ticks: sorted and compared by instant, as SQL Server compares <c>datetimeoffset</c>,
    /// at full precision. A value reads back at offset zero, the same instant. EF's <c>DateTimeOffsetToBinaryConverter</c>
    /// is not used: it stores the local clock time first, so values with different offsets sort by clock, not by instant.
    /// </summary>
    internal static readonly ValueConverter<DateTimeOffset, long> UtcTicks =
        new(v => v.UtcTicks, v => new DateTimeOffset(v, TimeSpan.Zero));

    /// <summary>Sets a new row version on every added or modified row that has one. The original value stays the concurrency check.</summary>
    internal static void SetRowVersions(ChangeTracker tracker)
    {
        foreach (var entry in tracker.Entries())
        {
            if (entry.State is not (EntityState.Added or EntityState.Modified)) continue;
            foreach (var property in entry.Metadata.GetProperties())
                if (property.FindAnnotation(AppSetRowVersion) is not null)
                    entry.Property(property).CurrentValue = NewRowVersion();
        }
    }

    /// <summary>A new row version, for a bulk update that does not go through the change tracker.</summary>
    internal static byte[] NewRowVersion() => RandomNumberGenerator.GetBytes(8);
}
